// 把 scripts/raw/{primary,junior,senior}_units.txt 编译为
// src/data/unitOrder.ts —— 每个学段单词的「册次+单元」排序键。
// 运行：node scripts/build-unit-order.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const __dirname = dirname(fileURLToPath(import.meta.url))
const root = join(__dirname, '..')
const rawDir = join(root, 'scripts', 'raw')

function norm(t) {
  return t.toLowerCase().replace(/\s+/g, ' ').trim()
}

function parse(file) {
  const text = readFileSync(join(rawDir, file), 'utf8')
  const out = []
  for (const line of text.split(/\r?\n/)) {
    if (!line.trim()) continue
    const parts = line.split('|')
    if (parts.length !== 3) continue
    const [book, unit, term] = parts.map((s) => s.trim())
    if (!book || !unit || !term) continue
    out.push({ book, unit, term: norm(term) })
  }
  return out
}

// 小学：YL-3A..YL-6B / PEP-3A..PEP-6B，三年级起点，每年级上下册各 8 单元
function keyPrimary(book, unit) {
  const m = /^([A-Z]+)-(\d)([AB])$/.exec(book)
  if (!m) return null
  const grade = +m[2] // 3..6
  const go = (grade - 3) * 2 + (m[3] === 'A' ? 0 : 1) // 0..7
  const un = /^U(\d+)$/.exec(unit)
  const u = un ? +un[1] : 99
  return { key: go * 10 + u, label: `${book} ${unit}` }
}

// 初中：7A..9B，每年级上下册各 8 单元
function keyJunior(book, unit) {
  const m = /^(\d)([AB])$/.exec(book)
  if (!m) return null
  const grade = +m[1] // 7..9
  const go = (grade - 7) * 2 + (m[2] === 'A' ? 0 : 1) // 0..5
  const un = /^U(\d+)$/.exec(unit)
  const u = un ? +un[1] : 99
  return { key: go * 10 + u, label: `${book} ${unit}` }
}

const SENIOR_BOOK = {
  必修一: 0,
  必修二: 1,
  必修三: 2,
  选必一: 3,
  选必二: 4,
  选必三: 5,
  选必四: 6,
}
// 高中：必修一→选必四，Welcome Unit=0，Unit1..5
function keySenior(book, unit) {
  const bo = SENIOR_BOOK[book]
  if (bo === undefined) return null
  let u
  if (unit === 'Welcome Unit') u = 0
  else {
    const m = /^Unit (\d+)$/.exec(unit)
    u = m ? +m[1] : 99
  }
  return { key: bo * 10 + u, label: `${book} ${unit}` }
}

function build(file, fn) {
  const rows = parse(file)
  const map = new Map()
  for (const r of rows) {
    const info = fn(r.book, r.unit)
    if (!info) continue
    const prev = map.get(r.term)
    // 同一词在多个册次/单元出现时，保留最早（key 最小）的那条
    if (!prev || info.key < prev.key) map.set(r.term, info)
  }
  return map
}

const primary = build('primary_units.txt', keyPrimary)
const junior = build('junior_units.txt', keyJunior)
const senior = build('senior_units.txt', keySenior)

function serialize(map) {
  const entries = [...map.entries()].sort((a, b) => a[1].key - b[1].key)
  const lines = entries.map(([term, info]) => {
    const t = JSON.stringify(term)
    return `    ${t}: { key: ${info.key}, label: ${JSON.stringify(info.label)} },`
  })
  return '{\n' + lines.join('\n') + '\n  }'
}

const ts = `// AUTO-GENERATED by scripts/build-unit-order.mjs — 请勿手改。
// 由 scripts/raw/{primary,junior,senior}_units.txt 编译而来，
// 为每个学段的单词提供「教材册次+单元」排序键，用于背诵时按 unit1,2,3… 顺序。
import type { Stage } from '../lib/types'

export interface UnitInfo {
  /** 学段内排序键：越小越靠前（册次/年级升序 → 单元升序） */
  key: number
  /** 人类可读的册次+单元标签，如 "YL-3A U1" / "7A U3" / "必修一 Unit 2" */
  label: string
}

export const UNIT_ORDER: Record<Stage, Record<string, UnitInfo>> = {
  primary: ${serialize(primary)},
  junior: ${serialize(junior)},
  senior: ${serialize(senior)},
}

/** 取某词在某学段下的单元标签（未匹配到返回 null）。 */
export function unitLabelOf(stage: Stage, term: string): string | null {
  return UNIT_ORDER[stage][term.toLowerCase()]?.label ?? null
}
`

writeFileSync(join(root, 'src', 'data', 'unitOrder.ts'), ts, 'utf8')
console.log(
  `unitOrder.ts written. primary=${primary.size} junior=${junior.size} senior=${senior.size}`,
)
